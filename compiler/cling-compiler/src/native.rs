//! Native host backend. Cling lowers the checked AST to C; Clang then performs
//! instruction selection, assembly, and linking for the host machine.
use std::collections::HashMap;
use crate::ast::*;

pub fn emit_c(program: &Program) -> String {
    let mut out = String::from("/* Generated by Cling. */\n#include <stdint.h>\n#include <stdbool.h>\n#include <stdio.h>\n#include <string.h>\n#include <inttypes.h>\n\nstatic void cling_print_int(int64_t x) { printf(\"%\" PRId64 \"\\n\", x); }\nstatic void cling_print_bool(bool x) { puts(x ? \"true\" : \"false\"); }\nstatic void cling_print_string(const char *x) { puts(x ? x : \"(null)\"); }\n\n");
    for f in &program.functions { out.push_str(&format!("{} {}({});\n", c_type(f.return_type), c_name(&f.name), c_params(&f.params))); }
    out.push('\n');
    let signatures: HashMap<String, TypeName> = program.functions.iter().map(|f| (f.name.clone(), f.return_type)).collect();
    for f in &program.functions {
        out.push_str(&format!("{} {}({}) {{\n", c_type(f.return_type), c_name(&f.name), c_params(&f.params)));
        let params = f.params.iter().map(|p| (p.name.clone(), p.ty)).collect();
        let mut emitter = Emitter { out: String::new(), indent: 1, scopes: vec![params], signatures: signatures.clone() };
        emitter.stmts(&f.body);
        out.push_str(&emitter.out);
        if f.return_type == TypeName::Void && !ends_return(&f.body) { out.push_str("    return;\n"); }
        out.push_str("}\n\n");
    }
    out.push_str("int main(void) { cling_fn_main(); return 0; }\n");
    out
}
fn c_type(t: TypeName) -> &'static str { match t { TypeName::Int => "int64_t", TypeName::Bool => "bool", TypeName::String => "const char *", TypeName::Void => "void" } }
fn c_name(n: &str) -> String { format!("cling_fn_{n}") }
fn c_var(n: &str) -> String { format!("cling_var_{n}") }
fn c_params(params: &[Parameter]) -> String { if params.is_empty() { "void".into() } else { params.iter().map(|p| format!("{} {}", c_type(p.ty), c_var(&p.name))).collect::<Vec<_>>().join(", ") } }
fn ends_return(body: &[Stmt]) -> bool { matches!(body.last(), Some(Stmt::Return { .. })) }
struct Emitter { out: String, indent: usize, scopes: Vec<HashMap<String, TypeName>>, signatures: HashMap<String, TypeName> }
impl Emitter {
    fn line(&mut self, s: impl AsRef<str>) { self.out.push_str(&"    ".repeat(self.indent)); self.out.push_str(s.as_ref()); self.out.push('\n'); }
    fn ty(&self, e: &Expr) -> TypeName {
        match &e.kind {
            ExprKind::Int(_) => TypeName::Int, ExprKind::Bool(_) => TypeName::Bool, ExprKind::String(_) => TypeName::String,
            ExprKind::Variable(n) => self.scopes.iter().rev().find_map(|s| s.get(n).copied()).unwrap_or(TypeName::Int),
            ExprKind::Call { callee, .. } if callee == "print" || callee == "log" => TypeName::Void,
            ExprKind::Call { callee, .. } => *self.signatures.get(callee).unwrap_or(&TypeName::Int),
            ExprKind::Unary { op, .. } => if *op == UnaryOp::Not { TypeName::Bool } else { TypeName::Int },
            ExprKind::Binary { op, .. } => match op { BinaryOp::Equal | BinaryOp::NotEqual | BinaryOp::Less | BinaryOp::LessEqual | BinaryOp::Greater | BinaryOp::GreaterEqual | BinaryOp::And | BinaryOp::Or => TypeName::Bool, _ => TypeName::Int },
        }
    }
    fn stmts(&mut self, statements: &[Stmt]) { for s in statements { self.stmt(s); } }
    fn stmt(&mut self, s: &Stmt) {
        match s {
            Stmt::Let { name, mutable, annotation, initializer, .. } => {
                let ty = annotation.unwrap_or_else(|| self.ty(initializer)); let expr = self.expr(initializer);
                let qualifier = if !*mutable && ty == TypeName::String { "const char * const".to_string() } else if !*mutable { format!("const {}", c_type(ty)) } else { c_type(ty).to_string() };
                self.line(format!("{qualifier} {} = {expr};", c_var(name)));
                self.scopes.last_mut().unwrap().insert(name.clone(), ty);
            }
            Stmt::Assign { name, value, .. } => { let expr = self.expr(value); self.line(format!("{} = {expr};", c_var(name))); }
            Stmt::Expr { expr, .. } => { let expr = self.expr(expr); self.line(format!("{expr};")); }
            Stmt::Return { value, .. } => if let Some(v) = value { let expr = self.expr(v); self.line(format!("return {expr};")); } else { self.line("return;"); },
            Stmt::If { condition, then_body, else_body, .. } => {
                let c = self.expr(condition); self.line(format!("if ({c}) {{")); self.indent += 1; self.scopes.push(HashMap::new()); self.stmts(then_body); self.scopes.pop(); self.indent -= 1;
                if else_body.is_empty() { self.line("}"); } else { self.line("} else {"); self.indent += 1; self.scopes.push(HashMap::new()); self.stmts(else_body); self.scopes.pop(); self.indent -= 1; self.line("}"); }
            }
            Stmt::While { condition, body, .. } => { let c = self.expr(condition); self.line(format!("while ({c}) {{")); self.indent += 1; self.scopes.push(HashMap::new()); self.stmts(body); self.scopes.pop(); self.indent -= 1; self.line("}"); }
            Stmt::Block { body, .. } => { self.line("{"); self.indent += 1; self.scopes.push(HashMap::new()); self.stmts(body); self.scopes.pop(); self.indent -= 1; self.line("}"); }
            Stmt::Pass { .. } => self.line(";"),
        }
    }
    fn expr(&mut self, e: &Expr) -> String {
        match &e.kind {
            ExprKind::Int(n) => format!("((int64_t){n})"), ExprKind::Bool(b) => b.to_string(), ExprKind::String(s) => format!("\"{}\"", escape_c(s)),
            ExprKind::Variable(n) => c_var(n),
            ExprKind::Unary { op, operand } => format!("({}{})", if *op == UnaryOp::Negate { "-" } else { "!" }, self.expr(operand)),
            ExprKind::Binary { op, left, right } => {
                let string_equality = matches!(op, BinaryOp::Equal | BinaryOp::NotEqual) && self.ty(left) == TypeName::String;
                let a = self.expr(left); let b = self.expr(right);
                if string_equality { return format!("(strcmp({a}, {b}) {} 0)", if *op == BinaryOp::Equal { "==" } else { "!=" }); }
                let operator = match op { BinaryOp::Add=>"+", BinaryOp::Subtract=>"-", BinaryOp::Multiply=>"*", BinaryOp::Divide=>"/", BinaryOp::Remainder=>"%", BinaryOp::Equal=>"==", BinaryOp::NotEqual=>"!=", BinaryOp::Less=>"<", BinaryOp::LessEqual=>"<=", BinaryOp::Greater=>">", BinaryOp::GreaterEqual=>">=", BinaryOp::And=>"&&", BinaryOp::Or=>"||" };
                format!("({a} {operator} {b})")
            }
            ExprKind::Call { callee, arguments } if callee == "print" || callee == "log" => {
                if let Some(arg) = arguments.first() { let ty = self.ty(arg); let value = self.expr(arg); let helper = match ty { TypeName::Int => "cling_print_int", TypeName::Bool => "cling_print_bool", TypeName::String => "cling_print_string", TypeName::Void => "cling_print_int" }; format!("{helper}({value})") } else { "cling_print_int(0)".into() }
            }
            ExprKind::Call { callee, arguments } => { let args = arguments.iter().map(|a| self.expr(a)).collect::<Vec<_>>().join(", "); format!("{}({args})", c_name(callee)) }
        }
    }
}
fn escape_c(s: &str) -> String { let mut out = String::new(); for c in s.chars() { match c { '\\'=>out.push_str("\\\\"), '"'=>out.push_str("\\\""), '\n'=>out.push_str("\\n"), '\r'=>out.push_str("\\r"), '\t'=>out.push_str("\\t"), '\0'=>out.push_str("\\000"), c if c.is_control() && (c as u32) <= 255 => out.push_str(&format!("\\{:03o}", c as u32)), c if c.is_control()=>{ let mut bytes=[0u8;4]; for b in c.encode_utf8(&mut bytes).as_bytes() { out.push_str(&format!("\\{:03o}", b)); } }, c=>out.push(c) } } out }

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{lexer, parser, sema};
    #[test]
    fn emits_native_control_flow_and_functions() {
        let src = "func twice(n: Int) -> Int { return n * 2; } func main() { var x: Int = twice(21); while x > 40 { print(x); x = x - 1; } }";
        let ast = parser::parse(lexer::lex(src).unwrap()).unwrap(); sema::check(&ast).unwrap(); let c = emit_c(&ast);
        assert!(c.contains("int64_t cling_fn_twice(int64_t cling_var_n)"));
        assert!(c.contains("while ((cling_var_x > ((int64_t)40)))"));
        assert!(c.contains("cling_print_int(cling_var_x)"));
        assert!(c.contains("int main(void)"));
    }
}
